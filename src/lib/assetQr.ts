import { buildEntityHash } from '@/lib/entityNavigation';

/**
 * Pure helpers for the asset QR deep link (Fase 1 · Punto 4). The QR payload
 * identity is ALWAYS assets.id — never assets.qr_code (reserved, unused in
 * this MVP) and never a name/code fallback. See docs/ASSET_QR.md.
 *
 * Nothing here talks to Supabase, the DOM, or the clipboard — that keeps
 * every function trivially testable from a throwaway Node script and keeps
 * the canonical URL construction in one place (reusing buildEntityHash, the
 * same builder every other deep link in the app goes through).
 */

const stripTrailingSlash = (origin: string): string => origin.replace(/\/+$/, '');

/**
 * Canonical, scannable URL for an asset: `<origin>/#assets?org=<uuid>&assetId=<uuid>`.
 * Depends on nothing but the two ids — never the asset's name, code, branch,
 * hierarchy, status or responsible, so renaming/re-coding/moving the asset
 * never invalidates a printed label. The explicit `/` before `#` is not
 * strictly required (browsers normalize `origin#hash` to `origin/#hash`
 * anyway), but it is spelled out so the printed/copied link always matches
 * the documented canonical form exactly.
 */
export const buildAssetQrUrl = (origin: string, organizationId: string, assetId: string): string =>
  `${stripTrailingSlash(origin)}/${buildEntityHash({ view: 'assets', organizationId, assetId })}`;

/** Lowercase, ASCII-only, hyphen-separated slug for use inside a filename.
 * Falls back to `activo` when nothing printable survives (e.g. a code made
 * only of symbols/emoji). */
export const sanitizeFilenameSegment = (value: string): string => {
  const slug = value
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '') // strip accents
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');
  return slug || 'activo';
};

/**
 * `qr-activo-<codigo-o-nombre-normalizado>-<uuid8>.<ext>` — code takes
 * priority over name (it's the shorter, more stable human label); the UUID
 * prefix guarantees two different assets with the same name/code never
 * collide, and it's still the source of truth if the slug gets edited later.
 */
export const buildAssetQrFilename = (
  asset: { id: string; name: string; code: string | null },
  extension: 'png' | 'svg',
): string => {
  const base = asset.code?.trim() || asset.name;
  const slug = sanitizeFilenameSegment(base);
  const shortId = asset.id.slice(0, 8);
  return `qr-activo-${slug}-${shortId}.${extension}`;
};

/** Strict HTML-escaping for values that end up inside the print label's
 * markup (asset name/code are free text the user typed). Order matters: `&`
 * must be escaped first, or escaping the other characters would re-escape
 * the entities this function itself just produced. */
export const escapeHtml = (value: string): string =>
  value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');

export interface AssetLabelHtmlInput {
  /** Trusted, already-serialized <svg>...</svg> markup — our own QRCodeSVG
   * render, never user input, so it is embedded as-is (escaping it would
   * print literal angle brackets instead of the QR code). */
  qrMarkup: string;
  name: string;
  code: string | null;
  /** Absolute URL to the local brand logo (never a remote/third-party URL). */
  logoUrl: string;
}

/**
 * Fixed 70mm × 40mm print label (MVP, not a label designer): a ~30mm QR on
 * the left, brand logo + asset name/code + a one-line hint on the right.
 * `name`/`code` are free text the user typed into the asset form, so they
 * are escaped before being embedded — everything else here is generated by
 * this app, never by the printed page's viewer.
 */
export const buildAssetLabelHtml = ({ qrMarkup, name, code, logoUrl }: AssetLabelHtmlInput): string => `<!doctype html>
<html lang="es">
<head>
<meta charset="utf-8" />
<title>Etiqueta QR</title>
<style>
  @page { size: 70mm 40mm; margin: 0; }
  * { box-sizing: border-box; }
  html, body { margin: 0; padding: 0; }
  body {
    width: 70mm; height: 40mm; padding: 3mm;
    display: flex; align-items: center; gap: 3mm;
    font-family: Arial, Helvetica, sans-serif; color: #111;
  }
  .qr { flex: 0 0 auto; width: 30mm; height: 30mm; }
  .qr svg { display: block; width: 100%; height: 100%; }
  .info { flex: 1 1 auto; min-width: 0; overflow: hidden; }
  .logo { display: block; height: 5mm; margin-bottom: 1.5mm; object-fit: contain; }
  .name { margin: 0 0 1mm; font-size: 9pt; font-weight: 700; line-height: 1.15; word-break: break-word; }
  .code { margin: 0 0 1.5mm; font-size: 7.5pt; color: #444; word-break: break-word; }
  .hint { margin: 0; font-size: 6.5pt; color: #666; }
</style>
</head>
<body>
  <div class="qr">${qrMarkup}</div>
  <div class="info">
    <img class="logo" src="${escapeHtml(logoUrl)}" alt="" />
    <p class="name">${escapeHtml(name)}</p>
    ${code ? `<p class="code">${escapeHtml(code)}</p>` : ''}
    <p class="hint">Escanea para abrir el activo</p>
  </div>
</body>
</html>`;
